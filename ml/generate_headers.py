"""Generate the P2.1 P4 wire and metadata layouts from frozen Python contracts."""

import argparse
import logging
from collections.abc import Sequence
from pathlib import Path

from common import contracts
from common.contracts import (
    CPU_HEADER_FIELDS,
    FEATURE_BIT_WIDTHS,
    FEATURE_ORDER,
    TREE_NODE_BITS,
    TrafficClass,
)

LOGGER = logging.getLogger(__name__)

# Ethernet, IPv4, TCP and UDP wire layouts are protocol fields, not experiment constants.
_WIRE_HEADERS = """header ethernet_t {
    bit<48> dst_addr;
    bit<48> src_addr;
    bit<16> ether_type;
}

header ipv4_t {
    bit<4> version;
    bit<4> ihl;
    bit<8> diffserv;
    bit<16> total_len;
    bit<16> identification;
    bit<3> flags;
    bit<13> frag_offset;
    bit<8> ttl;
    bit<8> protocol;
    bit<16> hdr_checksum;
    bit<32> src_addr;
    bit<32> dst_addr;
}

header tcp_t {
    bit<16> src_port;
    bit<16> dst_port;
    bit<32> seq_no;
    bit<32> ack_no;
    bit<4> data_offset;
    bit<3> reserved;
    bit<9> flags;
    bit<16> window;
    bit<16> checksum;
    bit<16> urgent_ptr;
}

header udp_t {
    bit<16> src_port;
    bit<16> dst_port;
    bit<16> length;
    bit<16> checksum;
}

header ipv4_options_t {
    varbit<320> data;
}

header tcp_options_t {
    varbit<320> data;
}

header tls_hello_fixed_t {
    bit<8> record_type;
    bit<16> record_version;
    bit<16> record_length;
    bit<8> handshake_type;
    bit<24> handshake_length;
    bit<16> client_version;
    bit<256> random;
    bit<8> session_length;
}

header tls_session_t { varbit<256> data; }
header tls_cipher_length_t { bit<16> value; }
header tls_ciphers_t { varbit<4096> data; }
header tls_compression_length_t { bit<8> value; }
header tls_compression_t { varbit<256> data; }
header tls_extensions_length_t { bit<16> value; }
header tls_extension_t {
    bit<16> kind;
    bit<16> length;
    varbit<8192> body;
}
"""


def generate_headers() -> str:
    """Return deterministic P4 definitions preserving §4.2–§4.3 field order and widths.

    This is one incremental include. Parser acceptance, fail-open packet handling, register
    ownership and QoS behavior are deliberately left to their responsible pipeline stages.
    """
    cpu_fields = "\n".join(f"    bit<{bits}> {name};" for name, bits in CPU_HEADER_FIELDS)
    features = "\n".join(
        f"    bit<{bits}> {name};"
        for name, bits in zip(FEATURE_ORDER, FEATURE_BIT_WIDTHS, strict=True)
    )
    classes = "\n".join(
        f"const bit<2> CLASS_{label.name} = {int(label)};" for label in TrafficClass
    )
    constants = "\n".join(
        f"const bit<32> {name} = {getattr(contracts, name)};"
        for name in (
            "FLOW_SLOTS",
            "CM_SKETCH_ROWS",
            "CM_SKETCH_COLUMNS",
            "FIRST_SIZE_COUNT",
            "WARMUP_PACKETS",
            "IDLE_TIMEOUT_US",
            "EWMA_SHIFT",
            "CONGESTION_HIGH_PACKETS",
            "CONGESTION_LOW_PACKETS",
            "FIRST_SIZE_LARGE_BYTES",
            "FLOW_AGE_SHIFT",
            "TLS_MAX_EXTENSIONS",
            "PROTO_META_EXT_COUNT_SHIFT",
            "PROTO_META_EXT_COUNT_MASK",
            "PROTO_META_PAYLOAD_SEEN",
            "FLOW_KEY_SLOT_SALT",
            "FLOW_KEY_TAG_SALT",
            "PUNT_REASON_FIRST_PACKET",
            "PUNT_REASON_LOW_CONFIDENCE",
            "CPU_CLONE_SESSION",
            "CPU_PORT",
            "TARGET_SWITCH_PORT",
            "FLOOD_GROUP",
            "GATEWAY_LAN_PORT",
            "GATEWAY_WAN_PORT",
        )
    )
    constants += "\n" + "\n".join(
        f"const bit<8> ALPN_{label.name} = {int(label)};" for label in contracts.AlpnClass
    )
    constants += "\n" + "\n".join(
        f"const bit<32> ECN_{label.name} = {treatment.ecn_threshold_pkts or 0};"
        for label, treatment in contracts.CLASS_TREATMENTS.items()
    )
    return (
        "// Generated by python -m ml.generate_headers; do not edit.\n"
        "// P2.1: design §4.2–§4.3 wire/feature layouts, §5.1 parser inputs.\n"
        "#ifndef AGENT_AWARE_HEADERS_P4\n#define AGENT_AWARE_HEADERS_P4\n\n"
        + classes
        + "\n"
        + constants
        + "\n\n"
        + _WIRE_HEADERS
        + "\nheader cpu_header_t {\n"
        + cpu_fields
        + "\n}\n\nstruct headers_t {\n"
        "    cpu_header_t cpu_header;\n"
        "    ethernet_t ethernet;\n"
        "    ipv4_t ipv4;\n"
        "    ipv4_options_t ipv4_options;\n"
        "    tcp_t tcp;\n"
        "    tcp_options_t tcp_options;\n"
        "    udp_t udp;\n"
        "    tls_hello_fixed_t tls_hello_fixed;\n"
        "    tls_session_t tls_session;\n"
        "    tls_cipher_length_t tls_cipher_length;\n"
        "    tls_ciphers_t tls_ciphers;\n"
        "    tls_compression_length_t tls_compression_length;\n"
        "    tls_compression_t tls_compression;\n"
        "    tls_extensions_length_t tls_extensions_length;\n"
        "    tls_extension_t[16] tls_extensions;\n"
        "}\n\nstruct features_t {\n" + features + "\n}\n\nstruct metadata_t {\n"
        "    features_t features;\n" + f"    bit<{TREE_NODE_BITS}> tree_node;\n"
        "    @field_list(1) bit<2> traffic_class;\n"
        "    bit<1> feature_valid;\n"
        "    bit<1> key_valid;\n"
        "    bit<32> ip_header_bytes;\n"
        "    bit<32> transport_bytes;\n"
        "    bit<32> tcp_header_bytes;\n"
        "    bit<32> client_ip;\n"
        "    bit<32> server_ip;\n"
        "    bit<8> protocol;\n"
        "    bit<16> client_port;\n"
        "    bit<16> server_port;\n"
        "    @field_list(1) bit<16> flow_hash;\n"
        "    bit<32> flow_tag;\n"
        "    bit<1> upstream;\n"
        "    bit<1> new_flow;\n"
        "    bit<1> slot_owned;\n"
        "    @field_list(1) bit<8> punt_reason;\n"
        "    @field_list(1) bit<16> original_ingress_port;\n"
        "    bit<16> ecn_threshold;\n"
        "    bit<1> punt_requested;\n"
        "    bit<2> meter_id;\n"
        "    bit<32> meter_color;\n"
        "    bit<1> congestion;\n"
        "    bit<32> payload_bytes;\n"
        "    bit<8> tls_ext_count;\n"
        "    bit<8> tls_alpn_class;\n"
        "    bit<1> tls_parsed;\n"
        "    bit<1> tls_truncated;\n"
        "    bit<1> first_payload_hello;\n"
        "    bit<32> tls_remaining;\n"
        "    bit<32> tls_extensions_remaining;\n"
        "    bit<32> tls_extension_bytes;\n"
        "    bit<32> tls_extension_word;\n"
        "    bit<72> tls_alpn_short;\n"
        "    bit<120> tls_alpn_long;\n"
        "}\n\n#endif\n"
    )


def main(argv: Sequence[str] | None = None) -> int:
    """Generate the include or check an existing artifact without overwriting it."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=Path("p4src/headers.p4"))
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    logging.basicConfig(level=logging.INFO, format="%(levelname)s %(name)s: %(message)s")
    source = generate_headers()
    try:
        if args.check:
            if args.output.read_text(encoding="utf-8") != source:
                LOGGER.error("P4 header layout drift: %s", args.output)
                return 1
        else:
            args.output.write_text(source, encoding="utf-8")
    except (OSError, UnicodeError) as exc:
        LOGGER.error("cannot %s %s: %s", "check" if args.check else "write", args.output, exc)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
